import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  ensureAdaptorMcpServers,
  ensurePiHarnessAgentSettings,
  ensureTokenjuicePiExtension,
} from "./managed-runtime.js";

describe("ensureTokenjuicePiExtension", () => {
  const tempDirs: string[] = [];

  afterEach(() => {
    for (const dir of tempDirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("installs OpenClaw tokenjuice into the managed Pi agent extensions directory", () => {
    const piAgentDir = mkdtempSync(join(tmpdir(), "openclaw-pi-agent-"));
    tempDirs.push(piAgentDir);

    const extensionPath = ensureTokenjuicePiExtension({ piAgentDir });

    expect(extensionPath).toBe(join(piAgentDir, "extensions", "tokenjuice.js"));
    const source = readFileSync(extensionPath!, "utf8");
    expect(source).toContain("tokenjuice pi extension");
    expect(source).toContain("generated by OpenClaw pi-fork");
    expect(source).toContain("createTokenjuicePiExtension");
    expect(source).toContain('event.toolName === "exec_command"');
    expect(source).toContain('event.toolName === "write_stdin"');
    expect(source).toContain("extractCodexVisibleText");
    expect(source).toContain("export default createTokenjuicePiExtension(config);");
  });
});

describe("ensurePiHarnessAgentSettings", () => {
  const tempDirs: string[] = [];

  afterEach(() => {
    for (const dir of tempDirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("writes a managed Pi settings file that pins the headless harness package", async () => {
    const piAgentDir = mkdtempSync(join(tmpdir(), "openclaw-pi-agent-"));
    const packageDir = mkdtempSync(join(tmpdir(), "my-pi-harness-"));
    tempDirs.push(piAgentDir, packageDir);
    mkdirSync(join(packageDir, "src"), { recursive: true });

    // Pins an explicit adaptorTools override so this schema-regression test
    // stays fully deterministic regardless of whether dist/mcp/*.js happens
    // to be built on the machine running it — resolveAdaptorToolsCatalog
    // returns config.adaptorTools verbatim when it's non-empty, bypassing
    // live MCP resolution entirely (that live-query path is covered in
    // adaptor-catalog.test.ts instead).
    const settingsPath = await ensurePiHarnessAgentSettings({
      piAgentDir,
      myPiHarnessPackagePath: packageDir,
      adaptorTools: [{ name: "oc__manual__x", server: "manual", tool: "x" }],
    });

    expect(settingsPath).toBe(join(piAgentDir, "settings.json"));
    expect(JSON.parse(readFileSync(settingsPath, "utf8"))).toEqual({
      defaultProvider: "claude-bridge",
      defaultModel: "claude-opus-4-8",
      defaultThinkingLevel: "off",
      enabledModels: ["claude-bridge/*", "openai-codex/*", "openai/*"],
      packages: [packageDir],
      extensions: {
        "native-tool-overrides": {
          exclude: ["Agent"],
          eager: ["TaskBackgroundList", "TaskStop"],
        },
        "openclaw-adaptor": {
          tools: [{ name: "oc__manual__x", server: "manual", tool: "x" }],
        },
      },
    });
    const modelsPath = join(piAgentDir, "models.json");
    expect(existsSync(modelsPath)).toBe(true);
    expect(JSON.parse(readFileSync(modelsPath, "utf8"))).toMatchObject({
      providers: {
        "claude-bridge": {
          baseUrl: "http://127.0.0.1:9100",
          models: [{ id: "claude-opus-4-8" }],
        },
        "openai-codex": {
          api: "openai-codex-responses",
          models: [{ id: "gpt-5.5" }, { id: "gpt-5.4" }, ...Array(4).fill({})],
        },
        openai: {
          api: "openai-codex-responses",
        },
      },
    });
  });

  it("honors configured native-tool eager overrides for profile-specific tool visibility", async () => {
    const piAgentDir = mkdtempSync(join(tmpdir(), "openclaw-pi-agent-"));
    const packageDir = mkdtempSync(join(tmpdir(), "my-pi-harness-"));
    tempDirs.push(piAgentDir, packageDir);
    mkdirSync(join(packageDir, "src"), { recursive: true });

    const settingsPath = await ensurePiHarnessAgentSettings({
      piAgentDir,
      myPiHarnessPackagePath: packageDir,
      nativeToolEager: [],
    });

    expect(JSON.parse(readFileSync(settingsPath, "utf8"))).toMatchObject({
      extensions: {
        "native-tool-overrides": { exclude: ["Agent"] },
      },
    });
    expect(
      JSON.parse(readFileSync(settingsPath, "utf8")).extensions["native-tool-overrides"].eager,
    ).toBeUndefined();
  });

  it("honors a configured defaultThinkingLevel (ISSUE-140: adaptive-only models reject thinking disabled)", async () => {
    const piAgentDir = mkdtempSync(join(tmpdir(), "openclaw-pi-agent-"));
    const packageDir = mkdtempSync(join(tmpdir(), "my-pi-harness-"));
    tempDirs.push(piAgentDir, packageDir);
    mkdirSync(join(packageDir, "src"), { recursive: true });

    const settingsPath = await ensurePiHarnessAgentSettings({
      piAgentDir,
      myPiHarnessPackagePath: packageDir,
      defaultThinkingLevel: "adaptive",
    });

    expect(JSON.parse(readFileSync(settingsPath, "utf8"))).toMatchObject({
      defaultThinkingLevel: "adaptive",
    });
  });
});

describe("ensureAdaptorMcpServers", () => {
  const tempDirs: string[] = [];

  afterEach(() => {
    for (const dir of tempDirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("merges bridge MCP servers without clobbering existing workspace servers", () => {
    const workspaceDir = mkdtempSync(join(tmpdir(), "openclaw-workspace-"));
    tempDirs.push(workspaceDir);
    mkdirSync(join(workspaceDir, "config"), { recursive: true });
    writeFileSync(
      join(workspaceDir, "config", "mcporter.json"),
      JSON.stringify(
        {
          mcpServers: {
            qmd: { command: "node", args: ["qmd.js"] },
          },
          imports: [],
        },
        null,
        2,
      ) + "\n",
    );

    const ok = ensureAdaptorMcpServers(workspaceDir, {
      "openclaw-tools": {
        command: process.execPath,
        args: ["openclaw-tools-serve.js"],
        cwd: "/app",
      },
    });

    expect(ok).toBe(true);
    expect(JSON.parse(readFileSync(join(workspaceDir, "config", "mcporter.json"), "utf8"))).toEqual(
      {
        mcpServers: {
          qmd: { command: "node", args: ["qmd.js"] },
          "openclaw-tools": {
            command: process.execPath,
            args: ["openclaw-tools-serve.js"],
            cwd: "/app",
          },
        },
        imports: [],
      },
    );
  });

  it("refuses to mutate malformed mcporter.json so callers can avoid exposing unbacked tools", () => {
    const workspaceDir = mkdtempSync(join(tmpdir(), "openclaw-workspace-"));
    tempDirs.push(workspaceDir);
    const mcporterPath = join(workspaceDir, "config", "mcporter.json");
    mkdirSync(join(workspaceDir, "config"), { recursive: true });
    writeFileSync(mcporterPath, "{not-json\n");

    const ok = ensureAdaptorMcpServers(workspaceDir, {
      "openclaw-tools": {
        command: process.execPath,
        args: ["openclaw-tools-serve.js"],
        cwd: "/app",
      },
    });

    expect(ok).toBe(false);
    expect(readFileSync(mcporterPath, "utf8")).toBe("{not-json\n");
  });
});

describe("plugin manifest config schema", () => {
  // 2026-06-10 ISSUE-140: configSchema has additionalProperties:false — any
  // PiHarnessConfig key missing from the manifest crashes the gateway at boot
  // ("must not have additional properties"). Keep schema and config.ts in sync.
  it("declares pi-fork config keys that affect managed spawn behavior", () => {
    const manifest = JSON.parse(readFileSync(join(__dirname, "openclaw.plugin.json"), "utf8"));
    expect(manifest.configSchema.properties.defaultThinkingLevel).toEqual({
      type: "string",
      enum: ["off", "minimal", "low", "medium", "high", "xhigh", "adaptive"],
      default: "off",
    });
    expect(manifest.configSchema.properties.downstreamProvidersByModel).toEqual({
      type: "object",
      additionalProperties: { type: "string" },
      default: {},
    });
    expect(manifest.configSchema.properties.nativeToolEager).toEqual({
      type: "array",
      items: { type: "string" },
      default: ["TaskBackgroundList", "TaskStop"],
    });
  });
});
